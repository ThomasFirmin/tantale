//! Defines the raw outputs of the user-defined function to optimize.
//!
//! An [`Outcome`] is a user-defined struct describing the output of
//! the objective function. This output may include optimized values, constraints,
//! evaluation cost, fidelities, and additional metadata (e.g. timing, seeds, or
//! debug information).
//!
//! # Relation to [Codomain](Outcome::Cod)
//!
//! The fields of an [`Outcome`] are used by the associated [`Codomain`]
//! to extract the values to optimize, constraints, and cost.
//! The codomain defines how to interpret the outcome fields and compute the optimization metrics.
//! For example, fields marked with `#[maximize]` or `#[minimize]` are used to compute the objective value,
//! while fields marked with `#[constraint]` are used to compute constraint violations.
//!
//! # Notes
//!
//! ## Codomain design
//!
//! The associated [`Codomain`] type of an [`Outcome`] is automatically
//! generated by the `Outcome` derive macro, via helper attributes on the fields of the struct.
//! Marked fields should be `f64` for objectives, constraints and cost, and any type for metadata.
//! Special `#[step]` should be unique and of type [`Step`](crate::Step).
//!
//! ## Serialization and recording
//! An [`Outcome`] must be serializable for checkpointing and
//! compatible with recording [`Schema`] and [`Recordable`].
//!
//! ## Multi-fidelity outputs
//! A [`FidOutcome`] is an [`Outcome`]
//! that exposes an [`EvalStep`], describing the current evaluation
//! state. It is used in multi-[`Fidelity`](crate::solution::partial::Fidelity) optimization and
//! [`MultiStep`](crate::objective::MultiStep) objectives. See [`Step`](crate::objective::Step) for the public states.
//!
//! # Example
//!
//! See the crate-level documentation for complete, tested usage examples.
//!
//! # Implementing Outcome and FidOutcome by hand
//!
//! See the crate-level documentation for complete, tested usage examples.
use crate::{
    Codomain, SolId,
    objective::EvalStep,
    utils::record::{Recordable, Schema},
};
use serde::{Deserialize, Serialize};
use std::{fmt::Debug, path::PathBuf};

/// Trait implemented by objective outputs.
///
/// An [`Outcome`] is expected to be a named-field struct carrying the values used by
/// the [`Codomain`] (objectives, constraints, cost,
/// or any metadata). It must be serializable for checkpointing and implements [`Schema`] and [`Recordable`].
///
/// The `Outcome` trait is automatically implemented by the `Outcome` derive macro,
/// which also generates the associated codomain type and implementation based on field attributes.
///
/// # Associated Derive Macro
///
/// The [`Outcome`] trait is automatically implemented by the
/// `Outcome` derive macro.
/// It implements [`Outcome`] for any struct with named fields that also implements
/// [`Debug`], [`Serialize`], and [`Deserialize`].
/// It also implements [`Recordable`] and [`Schema`] for recording the outputs.
pub trait Outcome
where
    Self: Debug
        + Schema<(), Parts = ()>
        + Recordable<(), Parts = ()>
        + Serialize
        + for<'de> Deserialize<'de>
        + Send
        + Sync,
{
    /// The associated codomain type of the outcome, automatically generated by the `Outcome` derive macro.
    /// The codomain defines how to interpret the fields of the outcome and extract the optimization metrics.
    type Cod: Codomain<Self>;
    /// Returns the associated codomain of the outcome, automatically generated by the `Outcome` derive macro.
    fn codomain() -> Self::Cod;
}

/// Trait for multi-fidelity outcomes.
///
/// A [`FidOutcome`] extends [`Outcome`] by exposing the current [`EvalStep`], which
/// indicates whether the evaluation is [`Pending`](crate::objective::Step::Pending),
/// [`Partially`](crate::objective::Step::Partially), [`Evaluated`](crate::objective::Step::Evaluated),
/// [`Discard`](crate::objective::Step::Discard). The internal `EvalStep::error()` marker is not a `Step` variant.
/// This is required by multi-[`Fidelity`](crate::solution::partial::Fidelity) optimization
/// and [`MultiStep`](crate::objective::MultiStep) objectives.
pub trait FidOutcome: Outcome
where
    Self: Sized + Debug + Serialize + for<'de> Deserialize<'de>,
{
    fn get_step(&self) -> EvalStep;
}

/// Marker trait for internal function state in [`MultiStep`](crate::objective::MultiStep) functions.
///
/// This represents the per-[`Solution`](crate::solution::Solution) evaluation state carried between
/// [`Step`](crate::objective::Step)s of a multi-[`Fidelity`](crate::solution::partial::Fidelity)
/// objective. The state is provided back to the [`MultiStep`](crate::objective::MultiStep) function
/// on the next call and can hold any serializable data needed to resume evaluation.
pub trait FuncState
where
    Self: Sized,
{
    /// Saves the function state within a folder for checkpointing.
    /// # Parameters
    /// - `path`: Folder path where the checkpoint is stored.
    ///   The user can decide how to serialize the state (e.g., using rmp_serde, bincode, etc.).
    fn save(&self, path: PathBuf) -> std::io::Result<()>;
    /// Loads the function state from a folder for checkpointing.
    /// # Parameters
    /// - `path`: Folder path where the checkpoint is stored.
    ///   The user can decide how to deserialize the state (e.g., using rmp_serde, bincode, etc.).
    fn load(path: PathBuf) -> std::io::Result<Self>;
}

pub struct IdOut<'a, Id: SolId, Out: Outcome>(pub &'a Id, pub &'a Out);

impl<'a, Id: SolId, Out: Outcome> Schema<()> for IdOut<'a, Id, Out> {
    type Parts = ();

    fn columns(_context: &(), _part: Self::Parts) -> Vec<String> {
        let mut col_id = Id::columns(&(), ());
        let mut col_out = Out::columns(&(), ());
        col_id.append(&mut col_out);
        col_id
    }
}

impl<'a, Id: SolId, Out: Outcome> Recordable<()> for IdOut<'a, Id, Out> {
    type Parts = ();
    fn record(&self, _context: &(), _part: Self::Parts) -> Vec<String> {
        let mut rec_id = self.0.record(&(), ());
        let mut rec_out = self.1.record(&(), ());
        rec_id.append(&mut rec_out);
        rec_id
    }
}
